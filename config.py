_last_pick: dict[tuple[str, ...], str] = {}


def pick(choices: list[str]) -> str:
    """맞장구 변형 중 하나를 고른다. **직전에 쓴 것은 피한다.**

    맞장구를 하나로 고정하면 하루에 수십 번 똑같은 소리가 나서 자동응답기가
    된다. 그래서 여러 개를 돌려 쓴다.

    ⚠ 그냥 무작위로 고르면 안 된다. 4개 중 하나를 뽑으면 같은 말이 연달아
      두 번 나올 확률이 25% 다. 그게 한 번 들리는 순간 '변형이 있다'는 인상이
      통째로 깨진다 — 변형을 넣은 값을 못 받는다. 직전 것만 빼도 0% 가 된다.
    """
    if not choices:
        return ""
    if len(choices) == 1:
        return choices[0]
    key = tuple(choices)
    pool = [c for c in choices if c != _last_pick.get(key)] or list(choices)
    out = random.choice(pool)
    _last_pick[key] = out
    return out

