"""말끝을 한 문체로 맞춘다 — 답을 만드는 곳이 넷이어도 목소리는 하나다.

동백의 답은 네 군데서 나온다:
  · 데몬 고정 문구  ("멀리 계신 것 같아…")
  · 로컬 규칙       ("오늘 166건 처리했습니다")
  · 큐웬(게이트키퍼) ("…확인해 보시겠어요?")
  · 클로드          ("아, 그 말씀이셨네요")
각자 따로 만들어져서 말투가 제각각이었다 (2026-08-14 지적:
"로컬과 클로드가 대답하는 방식이 전혀 다른데"). 네 곳을 각각 고치면
새 문구가 생길 때마다 또 어긋난다.

그래서 길목에서 한 번에 맞춘다. 소리는 speak.say() 한 곳으로만 나가므로
(say 직접 스폰 금지가 이 저장소의 규칙이다) 거기서 걸러 두면 앞으로 누가
무슨 문구를 새로 만들어도 같은 말투로 나간다.

⚠ 뜻은 절대 건드리지 않는다. 바꾸는 건 **문장 끝의 어미 하나**뿐이다.
  숫자·이름·조사·문장 구조는 그대로 둔다 — 소리로만 듣는 사장님이
  숫자가 틀린 걸 알아챌 방법이 없기 때문이다.

⚠ 규칙으로 한다. 소형 모델에 맡기면 어미를 고치랬더니 내용을 바꾼다
  (게이트키퍼가 실제로 그런다). 규칙은 0초·0원이고 결과가 늘 같다.
"""

import re

# ─────────────────────────────────────────────────────────
# 어미 표 — 앞이 길수록 먼저 걸려야 하므로 긴 것부터 둔다
# ─────────────────────────────────────────────────────────
# "…하겠습니다" 를 "…합니다" 보다 먼저 보지 않으면 "하겠어요" 가 아니라
# "하겠습니다" 의 뒷부분만 바뀌어 "하겠어요" 대신 "하겠습니다"→"하겠해요"
# 같은 것이 나온다.
_RULES: list[tuple[re.Pattern, str]] = [
    # 의지·약속 — 가장 자주 나오고 가장 딱딱하게 들린다
    (re.compile(r"하겠습니다(?=[.!?\s]|$)"), "할게요"),
    (re.compile(r"드리겠습니다(?=[.!?\s]|$)"), "드릴게요"),
    (re.compile(r"겠습니다(?=[.!?\s]|$)"), "을게요"),
    # 과거·완료
    (re.compile(r"했습니다(?=[.!?\s]|$)"), "했어요"),
    (re.compile(r"됐습니다(?=[.!?\s]|$)"), "됐어요"),
    (re.compile(r"았습니다(?=[.!?\s]|$)"), "았어요"),
    (re.compile(r"었습니다(?=[.!?\s]|$)"), "었어요"),
    # 부정
    (re.compile(r"못했습니다(?=[.!?\s]|$)"), "못했어요"),
    (re.compile(r"않았습니다(?=[.!?\s]|$)"), "않았어요"),
    (re.compile(r"없습니다(?=[.!?\s]|$)"), "없어요"),
    (re.compile(r"있습니다(?=[.!?\s]|$)"), "있어요"),
    # 일반 현재
    (re.compile(r"습니다(?=[.!?\s]|$)"), "어요"),
    (re.compile(r"합니다(?=[.!?\s]|$)"), "해요"),
    # 명령·권유
    (re.compile(r"하십시오(?=[.!?\s]|$)"), "하세요"),
    # ⚠ "…시기 바랍니다" 는 앞 음절까지 같이 봐야 한다. '바랍니다' 만
    #   갈아끼우면 "확인해 보시기 바랍니다" 가 "확인해 보시기 주세요" 라는
    #   비문이 된다. 어미만 건드린다는 원칙이 여기선 한 글자 더 봐야 지켜진다.
    (re.compile(r"([가-힣])시기 바랍니다(?=[.!?\s]|$)"), r"\1세요"),
    # 의문
    (re.compile(r"습니까(?=[.!?\s]|$)"), "어요"),
    (re.compile(r"입니까(?=[.!?\s]|$)"), "이에요"),
]

# "…입니다" 는 앞 글자 받침에 따라 갈린다 — 규칙 표로는 못 하고 따로 본다.
_IPNIDA = re.compile(r"(.)입니다(?=[.!?\s]|$)")


# 숫자는 소리로 읽히므로 '읽은 소리' 의 받침을 봐야 한다.
# 5 는 '오' 라 받침이 없고(5예요), 1 은 '일' 이라 있다(1이에요).
_DIGIT_FINAL = {"0": True, "1": True, "2": False, "3": True, "4": False,
                "5": False, "6": True, "7": True, "8": True, "9": True}


def _has_final(ch: str) -> bool:
    """앞 글자에 받침이 있는가. 없으면 '예요', 있으면 '이에요'."""
    if ch in _DIGIT_FINAL:
        return _DIGIT_FINAL[ch]
    code = ord(ch)
    if not (0xAC00 <= code <= 0xD7A3):
        return True          # 영문·기호 뒤는 '이에요' 가 무난하다
    return (code - 0xAC00) % 28 != 0


def _fix_ipnida(m: re.Match) -> str:
    ch = m.group(1)
    return ch + ("이에요" if _has_final(ch) else "예요")


def apply(text: str) -> str:
    """문장 끝 어미만 구어체로 바꾼다. 뜻은 그대로.

    이미 구어체면 아무것도 안 바뀐다 — 클로드 답변은 대개 그대로 지나간다.
    """
    if not text:
        return text
    out = _IPNIDA.sub(_fix_ipnida, text)
    for rx, repl in _RULES:
        out = rx.sub(repl, out)
    return out
